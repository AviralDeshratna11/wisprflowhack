"""Submission package (.swarsub zip) builder and examiner-side loader.

Contents:
  manifest.json            ids, versions, file hashes, chain head, turn-source labels
  answers.json             final answers (text + structured blocks with accessible equivalents)
  answers.docx             readable Word export
  revision_history.json    full hash-chained revision log
  verification.json        alignments + review markers (neutral statuses, never a cheating score)
  diagrams/<q>.dot|.txt    diagram source + accessible adjacency list
  encrypted_audio/<turn>.bin + key_wrap.json   turn audio encrypted for the examiner key
"""
from __future__ import annotations

import hashlib
import io
import json
import os
import uuid
import zipfile
from dataclasses import dataclass, field
from pathlib import Path

from swarlekhak import __version__
from swarlekhak.contracts import CONTRACT_VERSION
from swarlekhak.engines.diagram import Diagram
from swarlekhak.engines.evidence_chain import verify_chain
from swarlekhak.examination.package import ExamPackage, PackageError, read_zip_safely
from swarlekhak.security import crypto
from swarlekhak.storage.db import Store, utc_now

SUBMISSION_FORMAT = 1


def _answers_docx(title: str, questions: list[dict], answers: dict[str, dict], labels: dict[str, list[str]]) -> bytes:
    from docx import Document
    doc = Document()
    doc.add_heading(title, 0)
    doc.add_paragraph("Generated by SwarLekhak. Dictated with Wispr Flow unless labelled otherwise. "
                      "Equations and diagrams include their accessible text equivalents.")
    for q in questions:
        doc.add_heading(f"Question {q['ordinal']}", level=1)
        doc.add_paragraph(q["text"]).italic = True
        a = answers.get(q["db_id"])
        if not a or (not a["text"].strip() and not a["blocks"]):
            doc.add_paragraph("(No answer)")
            continue
        src = labels.get(q["db_id"])
        if src:
            doc.add_paragraph(f"Input sources: {', '.join(sorted(set(src)))}")
        for para in a["text"].split("\n"):
            if para.strip():
                doc.add_paragraph(para)
        for b in a["blocks"]:
            if b["type"] == "equation":
                doc.add_paragraph(f"Equation: {b['linear']}")
                doc.add_paragraph(f"LaTeX: {b['latex']}   |   Spoken: {b['spoken']}")
            elif b["type"] == "diagram":
                doc.add_paragraph("Diagram (adjacency list):")
                for line in Diagram.from_block(b).adjacency_text().splitlines() or ["(empty)"]:
                    doc.add_paragraph(line, style="List Bullet")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def build_submission(store: Store, session_id: str, exam: ExamPackage, vault, out_dir: Path) -> str:
    existing = store.submission(session_id)
    if existing and Path(existing["path"]).exists():
        return existing["path"]          # idempotent: a retry returns the same package
    sub_id = existing["id"] if existing else f"sub_{uuid.uuid4().hex[:16]}"
    questions = store.questions(exam.exam_id)
    rows = {a["question_id"]: a for a in store.answers(session_id)}
    answers = {qid: {"text": r["text"], "blocks": json.loads(r["blocks_json"]), "current_revision": r["current_revision"]}
               for qid, r in rows.items()}
    revisions = store.revisions(session_id)
    ok, _, chain_msg = verify_chain(revisions)
    turns = store.turns(session_id)
    labels: dict[str, list[str]] = {}
    ans_to_q = {r["id"]: qid for qid, r in rows.items()}
    for t in turns:
        if t["status"] == "inserted":
            labels.setdefault(ans_to_q.get(t["answer_id"], ""), []).append(t["source"])
    for r in revisions:
        if r["event_type"] == "keyboard_edit":
            labels.setdefault(ans_to_q.get(r["answer_id"], ""), []).append("typed")

    files: dict[str, bytes] = {}
    files["answers.json"] = crypto.dumps({
        "exam_id": exam.exam_id, "session_id": session_id,
        "answers": [{"question_id": q["id"], "ordinal": q["ordinal"], "question_text": q["text"],
                     **answers.get(q["db_id"], {"text": "", "blocks": [], "current_revision": None}),
                     "input_sources": sorted(set(labels.get(q["db_id"], [])))} for q in questions]})
    files["answers.docx"] = _answers_docx(exam.manifest["title"], questions, answers, labels)
    files["revision_history.json"] = crypto.dumps({"chain_valid_at_export": ok, "chain_message": chain_msg,
                                                   "revisions": revisions})
    alignments = [dict(r) for r in store.all(
        "SELECT al.* FROM alignments al JOIN turns t ON t.id=al.turn_id WHERE t.session_id=?", (session_id,))]
    for a in alignments:
        a["spans"] = json.loads(a.pop("spans_json"))
    files["verification.json"] = crypto.dumps({
        "note": "Review markers are neutral prompts produced by comparing written text with an independent local "
                "speech recogniser. A disagreement is not evidence of misconduct, and agreement is not identity proof.",
        "turns": [{"id": t["id"], "answer_id": t["answer_id"], "question_id": ans_to_q.get(t["answer_id"]),
                   "source": t["source"], "status": t["status"], "start_sample": t["start_sample"],
                   "end_sample": t["end_sample"], "revision_before": t["revision_before"],
                   "revision_after": t["revision_after"], "created_utc": t["created_utc"]} for t in turns],
        "alignments": alignments, "reviews": store.reviews(sid=session_id),
        "consents": store.consents(session_id)})
    for q in questions:
        a = answers.get(q["db_id"])
        for b in (a or {}).get("blocks", []):
            if b["type"] == "diagram":
                d = Diagram.from_block(b)
                files[f"diagrams/q{q['ordinal']}.dot"] = d.to_dot().encode("utf-8")
                files[f"diagrams/q{q['ordinal']}.txt"] = d.adjacency_text().encode("utf-8")

    audio_note = "no audio"
    pub = exam.manifest.get("examiner_public_key")
    audio_index = []
    assets = store.audio_assets(session_id)
    if assets and pub:
        content_key = crypto.AESGCM.generate_key(bit_length=256)
        for a in assets:
            wav = vault.load_wav(a["path"])
            if hashlib.sha256(wav).hexdigest() != a["sha256"]:
                raise RuntimeError(f"evidence audio for turn {a['turn_id']} failed its integrity check")
            files[f"encrypted_audio/{a['turn_id']}.bin"] = crypto.encrypt(content_key, wav, a["turn_id"].encode())
            audio_index.append({"turn_id": a["turn_id"], "sha256_plain": a["sha256"], "sample_rate": a["sample_rate"],
                                "num_samples": a["num_samples"]})
        files["encrypted_audio/key_wrap.json"] = crypto.dumps(crypto.wrap_key(content_key, pub))
        files["encrypted_audio/index.json"] = crypto.dumps(audio_index)
        audio_note = f"{len(assets)} turn recordings encrypted for the examiner key"
    elif assets:
        audio_note = "audio NOT exported: the exam package has no examiner public key"

    manifest = {
        "format_version": SUBMISSION_FORMAT, "submission_id": sub_id, "exam_id": exam.exam_id,
        "exam_manifest_hash": exam.manifest_hash, "session_id": session_id, "created_utc": utc_now(),
        "app_version": __version__, "contract_version": CONTRACT_VERSION,
        "chain_head": revisions[-1]["hash"] if revisions else None, "chain_valid_at_export": ok,
        "turn_sources": sorted({t["source"] for t in turns}), "audio": audio_note,
        "files": {k: hashlib.sha256(v).hexdigest() for k, v in files.items()},
        "limitations": "Local hash chain detects later edits but is not a signature. Not identity proof. "
                       "Local timer is not tamper-resistant.",
    }
    files["manifest.json"] = crypto.dumps(manifest)

    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{exam.exam_id}-{sub_id}.swarsub"
    tmp = out.with_suffix(".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, data in files.items():
            zf.writestr(name, data)
    os.replace(tmp, out)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    store.record_submission(sub_id, session_id, str(out), digest)
    return str(out)


# ============================================================ examiner side
@dataclass
class SubmissionView:
    path: str
    manifest: dict
    answers: dict
    revisions: dict
    verification: dict
    files: dict[str, bytes]
    integrity: list[tuple[str, bool, str]] = field(default_factory=list)

    @property
    def integrity_ok(self) -> bool:
        return all(ok for _, ok, _ in self.integrity)


def open_submission(path: str | Path) -> SubmissionView:
    files = read_zip_safely(path)
    for req in ("manifest.json", "answers.json", "revision_history.json", "verification.json"):
        if req not in files:
            raise PackageError(f"missing {req}")
    manifest = json.loads(files["manifest.json"])
    checks: list[tuple[str, bool, str]] = []
    declared = manifest.get("files", {})
    for name, digest in declared.items():
        actual = hashlib.sha256(files.get(name, b"")).hexdigest() if name in files else None
        checks.append((f"file {name}", actual == digest, "hash matches" if actual == digest else
                       ("missing" if actual is None else "hash MISMATCH")))
    extra = set(files) - set(declared) - {"manifest.json"}
    checks.append(("no undeclared files", not extra, ", ".join(sorted(extra)) or "none"))
    revisions = json.loads(files["revision_history.json"])
    ok, idx, msg = verify_chain(revisions["revisions"])
    checks.append(("revision hash chain", ok, msg))
    head = revisions["revisions"][-1]["hash"] if revisions["revisions"] else None
    checks.append(("chain head matches manifest", head == manifest.get("chain_head"), str(head)[:16]))
    return SubmissionView(str(path), manifest, json.loads(files["answers.json"]), revisions,
                          json.loads(files["verification.json"]), files, checks)


def decrypt_turn_audio(view: SubmissionView, turn_id: str, private_key_pem: bytes) -> bytes:
    wrap = json.loads(view.files["encrypted_audio/key_wrap.json"])
    key = crypto.unwrap_key(wrap, crypto.load_private_key(private_key_pem))
    wav = crypto.decrypt(key, view.files[f"encrypted_audio/{turn_id}.bin"], turn_id.encode())
    index = {e["turn_id"]: e for e in json.loads(view.files["encrypted_audio/index.json"])}
    if hashlib.sha256(wav).hexdigest() != index[turn_id]["sha256_plain"]:
        raise ValueError("decrypted audio does not match its recorded hash")
    return wav
